"""Seeded synthetic inventory datasets with canonical manifests.

Every dataset is a pure function of its seed, scenario version, profile, and
the generator version below. All names, SKUs, prices, and attributes come from
fixed synthetic pools; no production identifier, credential, or confidential
value can appear in generated output.
"""

import json
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from decimal import Decimal
from enum import StrEnum
from hashlib import sha256
from typing import ClassVar, cast

from paritygrid.domain.models import (
    ConnectorId,
    InventoryAttributes,
    InventoryRecord,
    Money,
    UtcTimestamp,
)
from paritygrid.domain.models.money import CurrencyCode

DATASET_GENERATOR_VERSION = 1
DATASET_FORMAT_NAME = "paritygrid-synthetic-dataset"

MAX_DATASET_ROWS = 5_000
_MAX_SEED = 9_223_372_036_854_775_807
_MAX_SCENARIO_VERSION = 2_147_483_647
_LENGTH_BYTES = 8

# Fixed synthetic vocabulary. Names mix scripts deliberately so Unicode
# handling is exercised; none of the words reference a real product, person,
# or organization.
_NAME_ADJECTIVES: tuple[tuple[str, ...], ...] = (
    ("Amber", "Cobalt", "Delta", "Ember", "Flint", "Granite"),
    ("Янтарный", "Кобальтовый", "Дельтовый", "Малахитовый"),
    ("Πορφυρός", "Κόκκινος", "Ασημένιος"),
    ("琥珀色", "钴蓝色", "翡翠色"),
    ("Ámbar", "Cobáltico", "Émeraude"),
)
_NAME_NOUNS: tuple[tuple[str, ...], ...] = (
    ("Actuator", "Valve", "Sensor", "Coupling", "Impeller", "Manifold"),
    ("Клапан", "Датчик", "Муфта", "Коллектор"),
    ("Αντλία", "Βαλβίδα", "Αισθητήρας"),
    ("伺服阀", "压力表", "联轴器"),
    ("Válvula", "Pompe", "Kupplung"),
)
_SKU_PREFIXES = ("GRID", "PARITY", "SYNC", "FLUX", "NODE", "MERIDIAN")
_ATTRIBUTE_KEYS = ("color", "grade", "bin", "origin", "tier", "batch", "lane")
_ATTRIBUTE_VALUES = ("blue", "a-1", "b-12", "north-line", "青", "β-2", "gold", "k-9")
_CURRENCIES = ("USD", "EUR", "JPY")
_BOUNDARY_SKU_WORD = "BOUNDARY"
_MALFORMED_VARIANT_COUNT = 8


class DatasetError(ValueError):
    """Raised when a dataset seed, version, or profile is invalid."""


class RowRole(StrEnum):
    """Closed classification of one generated wire row."""

    VALID = "valid"
    DUPLICATE = "duplicate"
    MALFORMED = "malformed"
    BOUNDARY = "boundary"


@dataclass(frozen=True, slots=True)
class ScenarioSeed:
    """The exact integer seed that fixes every generated byte."""

    value: int

    def __post_init__(self) -> None:
        object.__setattr__(self, "value", _validate_seed(self.value))

    def __str__(self) -> str:
        return str(self.value)


@dataclass(frozen=True, slots=True)
class ScenarioVersion:
    """The explicit scenario generation this dataset belongs to."""

    value: int

    def __post_init__(self) -> None:
        object.__setattr__(self, "value", _validate_scenario_version(self.value))

    def __str__(self) -> str:
        return str(self.value)


@dataclass(frozen=True, slots=True)
class DatasetProfile:
    """Bounded shape of a generated dataset.

    ``record_count`` counts every emitted row. ``duplicate_count`` rows repeat
    an earlier valid row under a distinct source key, ``malformed_count`` rows
    deliberately violate the canonical record contract, and ``boundary_count``
    rows are valid records pinned at domain limits.
    """

    record_count: int = 48
    malformed_count: int = 4
    boundary_count: int = 3
    duplicate_count: int = 5

    MAX_ROWS: ClassVar[int] = MAX_DATASET_ROWS

    def __post_init__(self) -> None:
        for name in ("record_count", "malformed_count", "boundary_count", "duplicate_count"):
            value = _validate_profile_count(getattr(self, name), name)
            object.__setattr__(self, name, value)
        if self.record_count > MAX_DATASET_ROWS:
            raise DatasetError(f"record count must not exceed {MAX_DATASET_ROWS}")
        base_rows = self.record_count - self.duplicate_count
        if base_rows < 0:
            raise DatasetError("duplicate count must not exceed the record count")
        if self.malformed_count + self.boundary_count > base_rows:
            raise DatasetError("malformed and boundary rows must fit within the base rows")
        if self.duplicate_count > base_rows - self.malformed_count:
            raise DatasetError("duplicate sources must be valid or boundary base rows")

    def canonical_bytes(self) -> bytes:
        """Return the deterministic profile encoding used in the identity."""
        return canonical_json_bytes(
            {
                "boundary_count": self.boundary_count,
                "duplicate_count": self.duplicate_count,
                "malformed_count": self.malformed_count,
                "record_count": self.record_count,
            }
        )


type WireValue = str | int | Mapping[str, "WireValue"] | Sequence["WireValue"] | None
type WireObject = dict[str, WireValue]


@dataclass(frozen=True, slots=True)
class WireRow:
    """One emitted row with its role and closed JSON payload."""

    index: int
    role: RowRole
    payload: Mapping[str, WireValue]

    def payload_bytes(self) -> bytes:
        """Return the canonical deterministic encoding of this row."""
        return canonical_json_bytes(dict(self.payload))


@dataclass(frozen=True, slots=True)
class DatasetManifest:
    """Canonical identity and content summary of one generated dataset."""

    dataset_id: str
    generator_version: int
    seed: ScenarioSeed
    scenario_version: ScenarioVersion
    profile: DatasetProfile
    counts: Mapping[str, int]
    rows_sha256: str
    total_payload_bytes: int

    def canonical_bytes(self) -> bytes:
        """Return the byte-stable manifest document."""
        return canonical_json_bytes(
            {
                "counts": dict(self.counts),
                "dataset_id": self.dataset_id,
                "format": DATASET_FORMAT_NAME,
                "generator_version": self.generator_version,
                "profile": cast(
                    "dict[str, WireValue]",
                    json.loads(self.profile.canonical_bytes().decode("ascii")),
                ),
                "rows_sha256": self.rows_sha256,
                "scenario_version": self.scenario_version.value,
                "seed": self.seed.value,
                "total_payload_bytes": self.total_payload_bytes,
            }
        )


@dataclass(frozen=True, slots=True)
class SyntheticDataset:
    """A fully materialized deterministic dataset and its manifest."""

    seed: ScenarioSeed
    scenario_version: ScenarioVersion
    profile: DatasetProfile
    rows: tuple[WireRow, ...]
    manifest: DatasetManifest

    def rows_with_role(self, role: RowRole) -> tuple[WireRow, ...]:
        """Return emitted rows carrying one role in generation order."""
        return tuple(row for row in self.rows if row.role is role)

    def to_connector_record(self, row: WireRow, connector_id: ConnectorId) -> InventoryRecord:
        """Parse a valid-role row into the canonical domain record.

        Malformed rows intentionally raise the domain validation error that
        later normalization must quarantine.
        """
        if row.role is RowRole.MALFORMED:
            raise DatasetError("malformed rows do not parse as canonical records")
        return parse_wire_row(row.payload, connector_id=connector_id)


def canonical_json_bytes(value: Mapping[str, WireValue]) -> bytes:
    """Encode a closed JSON document deterministically."""
    return json.dumps(
        value,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("ascii")


def parse_wire_row(
    payload: Mapping[str, WireValue],
    *,
    connector_id: ConnectorId,
) -> InventoryRecord:
    """Build the canonical domain record from one wire payload."""
    unit_price = _require_mapping(payload.get("unit_price"), "unit_price")
    attributes = _require_mapping(payload.get("attributes"), "attributes")
    attribute_items: dict[str, str] = {}
    for key, attribute_value in attributes.items():
        if not isinstance(attribute_value, str):
            raise DatasetError("inventory attributes must be text pairs")
        attribute_items[key] = attribute_value
    return InventoryRecord.create(
        sku=_require_text(payload.get("sku"), "sku"),
        name=_require_text(payload.get("name"), "name"),
        quantity=_require_int(payload.get("quantity"), "quantity"),
        unit_price=Money.parse(
            f"{_require_text(unit_price.get('currency'), 'unit_price.currency')} "
            f"{_require_text(unit_price.get('amount'), 'unit_price.amount')}"
        ),
        updated_at=UtcTimestamp.parse(_require_text(payload.get("updated_at"), "updated_at")),
        connector_id=connector_id,
        source_record_key=_require_text(payload.get("source_record_key"), "source_record_key"),
        attributes=attribute_items,
    )


def generate_dataset(
    seed: ScenarioSeed,
    scenario_version: ScenarioVersion,
    profile: DatasetProfile | None = None,
) -> SyntheticDataset:
    """Generate the byte-stable dataset fixed by the seed and version."""
    effective_profile = profile if profile is not None else DatasetProfile()
    layout = _RowLayout.from_profile(seed, scenario_version, effective_profile)
    rows: list[WireRow] = []
    malformed_position = 0
    for base_index in range(layout.base_rows):
        role = layout.role_for(base_index)
        if role is RowRole.MALFORMED:
            rows.append(
                WireRow(
                    index=len(rows),
                    role=role,
                    payload=_malformed_payload(
                        seed,
                        scenario_version,
                        base_index,
                        variant=malformed_position % _MALFORMED_VARIANT_COUNT,
                    ),
                )
            )
            malformed_position += 1
            continue
        payload = _valid_payload(
            seed,
            scenario_version,
            base_index,
            boundary=role is RowRole.BOUNDARY,
            source_key=f"rec-{base_index:06d}",
        )
        rows.append(WireRow(index=len(rows), role=role, payload=payload))
        if base_index in layout.duplicate_sources:
            rows.append(
                WireRow(
                    index=len(rows),
                    role=RowRole.DUPLICATE,
                    payload=_duplicate_payload(payload, source_index=base_index),
                )
            )
    digest_stream = bytearray()
    total_payload_bytes = 0
    for row in rows:
        encoded = row.payload_bytes()
        digest_stream += _frame(row.index.to_bytes(_LENGTH_BYTES, byteorder="big"))
        digest_stream += _frame(encoded)
        total_payload_bytes += len(encoded)
    rows_sha256 = sha256(digest_stream).hexdigest()
    counts = {
        "boundary": sum(row.role is RowRole.BOUNDARY for row in rows),
        "duplicate": sum(row.role is RowRole.DUPLICATE for row in rows),
        "malformed": sum(row.role is RowRole.MALFORMED for row in rows),
        "total": len(rows),
        "valid": sum(row.role is RowRole.VALID for row in rows),
    }
    identity_preimage = (
        b"paritygrid-dataset-identity-v1\0"
        + _frame(DATASET_FORMAT_NAME.encode("ascii"))
        + _frame(str(DATASET_GENERATOR_VERSION).encode("ascii"))
        + _frame(str(seed.value).encode("ascii"))
        + _frame(str(scenario_version.value).encode("ascii"))
        + _frame(effective_profile.canonical_bytes())
        + _frame(rows_sha256.encode("ascii"))
    )
    manifest = DatasetManifest(
        dataset_id=sha256(identity_preimage).hexdigest(),
        generator_version=DATASET_GENERATOR_VERSION,
        seed=seed,
        scenario_version=scenario_version,
        profile=effective_profile,
        counts=counts,
        rows_sha256=rows_sha256,
        total_payload_bytes=total_payload_bytes,
    )
    return SyntheticDataset(
        seed=seed,
        scenario_version=scenario_version,
        profile=effective_profile,
        rows=tuple(rows),
        manifest=manifest,
    )


@dataclass(frozen=True, slots=True)
class _RowLayout:
    """Deterministic assignment of row roles to base row indices."""

    base_rows: int
    malformed_indices: frozenset[int]
    boundary_indices: frozenset[int]
    duplicate_sources: frozenset[int]

    @classmethod
    def from_profile(
        cls,
        seed: ScenarioSeed,
        scenario_version: ScenarioVersion,
        profile: DatasetProfile,
    ) -> _RowLayout:
        base_rows = profile.record_count - profile.duplicate_count
        malformed = _top_indices(
            seed, scenario_version, "malformed", profile.malformed_count, base_rows, frozenset()
        )
        boundary = _top_indices(
            seed,
            scenario_version,
            "boundary",
            profile.boundary_count,
            base_rows,
            malformed,
        )
        eligible_duplicate_sources = base_rows - len(malformed)
        duplicates = _top_indices(
            seed,
            scenario_version,
            "duplicate-source",
            min(profile.duplicate_count, eligible_duplicate_sources),
            base_rows,
            malformed,
        )
        return cls(
            base_rows=base_rows,
            malformed_indices=malformed,
            boundary_indices=boundary,
            duplicate_sources=duplicates,
        )

    def role_for(self, base_index: int) -> RowRole:
        if base_index in self.malformed_indices:
            return RowRole.MALFORMED
        if base_index in self.boundary_indices:
            return RowRole.BOUNDARY
        return RowRole.VALID


def _top_indices(
    seed: ScenarioSeed,
    scenario_version: ScenarioVersion,
    domain: str,
    count: int,
    base_rows: int,
    excluded: frozenset[int],
) -> frozenset[int]:
    """Select ``count`` deterministic indices by digest ranking."""
    if count == 0:
        return frozenset()
    scored = sorted(
        (_digest_rank(seed, scenario_version, domain, index), index)
        for index in range(base_rows)
        if index not in excluded
    )
    return frozenset(index for _rank, index in scored[:count])


def _digest_rank(
    seed: ScenarioSeed,
    scenario_version: ScenarioVersion,
    domain: str,
    index: int,
) -> tuple[int, int]:
    digest = _digest(seed.value, scenario_version.value, domain, index)
    return (int.from_bytes(digest[:8], byteorder="big"), index)


def _digest(seed_value: int, version_value: int, domain: str, index: int) -> bytes:
    payload = b"\0".join(
        (
            b"paritygrid-dataset-row-v1",
            str(seed_value).encode("ascii"),
            str(version_value).encode("ascii"),
            domain.encode("ascii"),
            str(index).encode("ascii"),
        )
    )
    return sha256(payload).digest()


def _word(digest: bytes, offset: int, pool: tuple[str, ...]) -> str:
    return pool[digest[offset] % len(pool)]


def _decimal_from_units(units: int, exponent: int) -> Decimal:
    text = str(units)
    if exponent == 0:
        return Decimal(text)
    return Decimal(f"{text[:-exponent]}.{text[-exponent:]}")


def _amount_text(amount: Money) -> str:
    return str(amount).split(" ", maxsplit=1)[1]


def _valid_payload(
    seed: ScenarioSeed,
    scenario_version: ScenarioVersion,
    base_index: int,
    *,
    boundary: bool,
    source_key: str,
) -> WireObject:
    digest = _digest(seed.value, scenario_version.value, "record", base_index)
    if boundary:
        return _boundary_payload(digest, base_index, source_key)
    script = digest[0] % len(_NAME_ADJECTIVES)
    name = f"{_word(digest, 1, _NAME_ADJECTIVES[script])} {_word(digest, 2, _NAME_NOUNS[script])}"
    sku = f"{_word(digest, 3, _SKU_PREFIXES)}-{base_index:04d}-{digest[4]:02X}{digest[5]:02X}"
    currency = _word(digest, 6, _CURRENCIES)
    units = 10 + int.from_bytes(digest[7:9], byteorder="big") % 500_000
    exponent = 0 if currency == "JPY" else 2
    amount = Money(
        amount=_decimal_from_units(units, exponent),
        currency=CurrencyCode.parse(currency),
        minor_unit_exponent=exponent,
    )
    microsecond = (digest[14] << 16) + (digest[15] << 8) + digest[16]
    updated_at = UtcTimestamp.parse(
        f"2024-{1 + digest[10] % 12:02d}-{1 + digest[9] % 28:02d}"
        f"T{digest[11] % 24:02d}:{digest[12] % 60:02d}:{digest[13] % 60:02d}"
        f".{microsecond % 1_000_000:06d}Z"
    )
    attributes: dict[str, str] = {}
    for slot in range(digest[17] % 4):
        key = _ATTRIBUTE_KEYS[(digest[18 + slot] + slot) % len(_ATTRIBUTE_KEYS)]
        attributes[key] = _ATTRIBUTE_VALUES[(digest[21 + slot] + slot) % len(_ATTRIBUTE_VALUES)]
    return {
        "attributes": dict(sorted(attributes.items())),
        "name": name,
        "quantity": int.from_bytes(digest[18:20], byteorder="big") % 1_000,
        "sku": sku,
        "source_record_key": source_key,
        "unit_price": {"amount": _amount_text(amount), "currency": currency},
        "updated_at": str(updated_at),
    }


def _boundary_payload(digest: bytes, base_index: int, source_key: str) -> WireObject:
    """Build a valid row pinned at canonical domain limits."""
    variant = digest[0] % 3
    currency = "USD"
    if variant == 0:
        name = ("Boundary " + "Value " * 38 + "End")[:160]
        sku = f"{_BOUNDARY_SKU_WORD}-{base_index:04d}-" + "X" * 50
        quantity = 2_147_483_647
        units = 1
        microsecond = 999_999
        attributes = {"grade": "boundary"}
    elif variant == 1:
        name = "Максимальная граница значения"
        sku = f"{_BOUNDARY_SKU_WORD}-{base_index:04d}-M1"
        quantity = 0
        units = 999_999_999_999_999
        microsecond = 0
        attributes = {"grade": "boundary"}
    else:
        name = "边界值检票口"
        sku = f"{_BOUNDARY_SKU_WORD}-{base_index:04d}-C3"
        quantity = 2_147_483_647
        units = 999_999
        microsecond = 1
        # Pin the attribute collection at its item limit inside the byte cap.
        attributes = {
            f"k{slot:02d}": f"v{(digest[1] + slot) % 10}"
            for slot in range(InventoryAttributes.MAX_ITEMS)
        }
    amount = Money(
        amount=_decimal_from_units(units, 2),
        currency=CurrencyCode.parse(currency),
        minor_unit_exponent=2,
    )
    updated_at = UtcTimestamp.parse(f"2024-06-15T12:00:00.{microsecond:06d}Z")
    return {
        "attributes": dict(sorted(attributes.items())),
        "name": name,
        "quantity": quantity,
        "sku": sku[:64],
        "source_record_key": source_key,
        "unit_price": {"amount": _amount_text(amount), "currency": currency},
        "updated_at": str(updated_at),
    }


def _malformed_payload(
    seed: ScenarioSeed,
    scenario_version: ScenarioVersion,
    base_index: int,
    *,
    variant: int,
) -> WireObject:
    """Build a row that deliberately violates one canonical contract rule."""
    digest = _digest(seed.value, scenario_version.value, "record", base_index)
    base_name = _word(digest, 1, _NAME_NOUNS[digest[0] % len(_NAME_NOUNS)])
    base_sku = f"GRID-{base_index:04d}"
    payload: WireObject = {
        "attributes": {"color": "blue"},
        "name": f"Broken {base_name}",
        "quantity": 7,
        "sku": base_sku,
        "source_record_key": f"bad-{base_index:06d}",
        "unit_price": {"amount": "12.34", "currency": "USD"},
        "updated_at": "2024-03-04T05:06:07.000000Z",
    }
    if variant == 0:
        payload["sku"] = base_sku.lower()
    elif variant == 1:
        del payload["name"]
    elif variant == 2:
        payload["quantity"] = -5
    elif variant == 3:
        payload["unit_price"] = {"amount": "12.3456789", "currency": "USD"}
    elif variant == 4:
        payload["name"] = f"Broken  {base_name}"
    elif variant == 5:
        payload["sku"] = "X" * 65
    elif variant == 6:
        payload["updated_at"] = "2024-13-40T99:99:99.999999Z"
    else:
        payload["attributes"] = {"Color": "upper-case-key"}
    return payload


def _duplicate_payload(payload: Mapping[str, WireValue], *, source_index: int) -> WireObject:
    duplicate = dict(payload)
    duplicate["source_record_key"] = f"dup-{source_index:06d}"
    return duplicate


def _require_text(value: WireValue, field: str) -> str:
    if not isinstance(value, str):
        raise DatasetError(f"{field} must be text")
    return value


def _require_int(value: WireValue, field: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise DatasetError(f"{field} must be an integer")
    return value


def _require_mapping(value: WireValue, field: str) -> Mapping[str, WireValue]:
    if not isinstance(value, dict):
        raise DatasetError(f"{field} must be an object")
    return value


def _validate_seed(value: object) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise DatasetError("scenario seed must be an integer")
    if not 1 <= value <= _MAX_SEED:
        raise DatasetError("scenario seed must be between 1 and 2^63-1")
    return value


def _validate_scenario_version(value: object) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise DatasetError("scenario version must be an integer")
    if not 1 <= value <= _MAX_SCENARIO_VERSION:
        raise DatasetError("scenario version must be between 1 and 2^31-1")
    return value


def _validate_profile_count(value: object, name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise DatasetError(f"{name} must be an integer")
    if value < 0:
        raise DatasetError(f"{name} must not be negative")
    return value


def _frame(value: bytes) -> bytes:
    return len(value).to_bytes(_LENGTH_BYTES, byteorder="big") + value
